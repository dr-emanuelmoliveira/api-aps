def treinar_modelos(X, y_class, y_reg, codigo_indicador):
    """Treina o classificador e o regressor Random Forest."""
    config = INDICADORES[codigo_indicador]

    #
    # Verificar viabilidade do split estratificado
    #
    contagem_classes = y_class.value_counts()
    classes_minimas = contagem_classes[contagem_classes < 2]

    usar_stratify = True
    if len(classes_minimas) > 0:
        print(f"\n   ⚠️  Classes com apenas 1 amostra detectadas: "
              f"{dict(classes_minimas)}")
        print(f"   → Usando split NÃO estratificado para este indicador.\n")
        usar_stratify = False

    # Split treino/teste
    if usar_stratify:
        X_train, X_test, y_train, y_test = train_test_split(
            X, y_class, test_size=0.2, random_state=42, stratify=y_class
        )
    else:
        X_train, X_test, y_train, y_test = train_test_split(
            X, y_class, test_size=0.2, random_state=42
        )

    # --- Classificador de Prioridade ---
    clf = RandomForestClassifier(
        n_estimators=200, max_depth=10, random_state=42, class_weight='balanced'
    )
    clf.fit(X_train, y_train)

    y_pred = clf.predict(X_test)
    acc = accuracy_score(y_test, y_pred)

    print(f"\n{'='*50}")
    print(f"  CLASSIFICADOR DE PRIORIDADE — {codigo_indicador}")
    print(f"{'='*50}")
    print(f"  Acurácia: {acc:.2%}")
    print(f"  Split: {'estratificado' if usar_stratify else 'não estratificado'}")
    print(f"\n  Relatório de Classificação:")
    print(classification_report(y_test, y_pred, zero_division=0))

    # --- Regressor de Dias até Consulta ---
    y_reg_train = y_reg.loc[X_train.index]
    y_reg_test = y_reg.loc[X_test.index]

    reg = RandomForestRegressor(
        n_estimators=200, max_depth=10, random_state=42
    )
    reg.fit(X_train, y_reg_train)

    y_reg_pred = reg.predict(X_test)
    mae = np.mean(np.abs(y_reg_test - y_reg_pred))

    print(f"\n{'='*50}")
    print(f"  REGRESSOR DE DIAS ATÉ CONSULTA — {codigo_indicador}")
    print(f"{'='*50}")
    print(f"  MAE (Erro Médio Absoluto): {mae:.1f} dias")

    return clf, reg, X_test, y_test, y_pred

