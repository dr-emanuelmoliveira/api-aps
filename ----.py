def _calcular_idade_data_nasc(data_nasc):
    """Calcula idade em anos a partir da data de nascimento."""
    if pd.isna(data_nasc) or str(data_nasc).strip() == '':
        return 0
    data = _parse_data(data_nasc)
    if data is None or pd.isna(data):
        return 0
    hoje = datetime.now()
    idade = hoje.year - data.year
    if (hoje.month, hoje.day) < (data.month, data.day):
        idade -= 1
    if idade < 0 or idade > 130:
        return 0
    return float(idade)

