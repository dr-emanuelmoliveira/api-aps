def detectar_indicador(colunas_csv):
    """
    Analisa as colunas do CSV e identifica qual indicador
    (C2, C3, C4, C5, C6, C7) corresponde aos dados.

    Sistema de pontuação em 3 níveis:
    1. Padrões decisivos (+10): termos exclusivos de cada indicador
    2. Padrões regulares (+1): termos compartilhados entre indicadores
    3. Exclusões (-5): termos de OUTROS indicadores presentes no CSV
    """
    colunas_norm = [_normalizar_texto(c) for c in colunas_csv]
    scores = {}
    detalhes = {}  # Para debug

    for codigo, config in INDICADORES.items():
        score = 0
        pontos_decisivos = 0
        pontos_regulares = 0
        penalidades = 0

        #
        # NÍVEL 1: Padrões decisivos (+10 cada)
        # Termos EXCLUSIVOS de um indicador que não aparecem em outros
        #
        padroes_decisivos = config.get("padroes_decisivos", [])
        for padrao in padroes_decisivos:
            padrao_norm = _normalizar_texto(padrao)
            for col in colunas_norm:
                if padrao_norm in col:
                    score += 10
                    pontos_decisivos += 10
                    break

        #
        # NÍVEL 2: Padrões regulares (+1 cada)
        # Termos compartilhados entre indicadores
        #
        for padrao in config["colunas_detectar"]:
            padrao_norm = _normalizar_texto(padrao)
            for col in colunas_norm:
                if padrao_norm in col:
                    score += 1
                    pontos_regulares += 1
                    break

        #
        # NÍVEL 3: Exclusões (-5 cada)
        # Termos de OUTROS indicadores que não deveriam estar presentes
        #
        if "colunas_excluir" in config:
            for padrao_excluir in config["colunas_excluir"]:
                padrao_excluir_norm = _normalizar_texto(padrao_excluir)
                for col in colunas_norm:
                    if padrao_excluir_norm in col:
                        score -= 5
                        penalidades -= 5
                        break

        scores[codigo] = score
        detalhes[codigo] = {
            'decisivos': pontos_decisivos,
            'regulares': pontos_regulares,
            'penalidades': penalidades,
            'total': score
        }

    #
    # Print detalhado para debug
    #
    print(f"\n{'='*70}")
    print(f"  DETECÇÃO AUTOMÁTICA DE INDICADOR")
    print(f"  Colunas no CSV: {len(colunas_csv)}")
    print(f"{'='*70}")
    print(f"  {'Indicador':<40} {'Decis.':>6} {'Regul.':>6} {'Penal.':>6} {'TOTAL':>6}")
    print(f"  {'─'*68}")

    melhor_codigo = max(scores, key=scores.get)
    for codigo in sorted(scores.keys()):
        d = detalhes[codigo]
        marker = " ◄◄◄ SELECIONADO" if codigo == melhor_codigo else ""
        print(f"  {codigo} — {INDICADORES[codigo]['nome']:<34} "
              f"{d['decisivos']:>5}  {d['regulares']:>5}  "
              f"{d['penalidades']:>5}  {d['total']:>5}{marker}")

    if scores[melhor_codigo] <= 0:
        print(f"\n  ⚠️  Nenhum indicador teve score positivo!")
        print(f"  Colunas do CSV (normalizadas):")
        for c in colunas_norm:
            print(f"    • {c}")
        raise ValueError(
            "Não foi possível detectar o indicador. "
            "Verifique se o CSV contém as colunas esperadas."
        )

    print(f"\n  ✅ INDICADOR DETECTADO: {melhor_codigo} — "
          f"{INDICADORES[melhor_codigo]['nome']}")
    print(f"{'='*70}\n")

    return melhor_codigo

