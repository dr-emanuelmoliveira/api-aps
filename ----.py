def prever_consultas(clf, reg, X, features, codigo_indicador):
    """Prevê datas de consulta para todos os pacientes."""
    prioridade_pred = clf.predict(X)
    dias_pred = reg.predict(X)
    dias_pred = np.maximum(dias_pred, 1).astype(int)

    hoje = datetime.now()
    datas_previstas = [hoje + timedelta(days=int(d)) for d in dias_pred]
    dias_semana = ['Seg', 'Ter', 'Qua', 'Qui', 'Sex', 'Sáb', 'Dom']

    resultado = features.copy()
    resultado['Prioridade_Predita'] = prioridade_pred
    resultado['Data Prevista Consulta'] = [d.strftime('%d/%m/%Y') for d in datas_previstas]
    resultado['Dias até Consulta'] = dias_pred
    resultado['Dia da Semana'] = [dias_semana[d.weekday()] for d in datas_previstas]

    return resultado

