def criar_features_ml(df_resultado, dados_originais, codigo_indicador):
    """Cria features para treinar o modelo de ML."""
    config = INDICADORES[codigo_indicador]
    features = df_resultado.copy()

    # Codificar microárea
    le_micro = LabelEncoder()
    features['microarea_cod'] = le_micro.fit_transform(features['Microárea'].astype(str))

    # Score de urgência temporal (inverso da completude)
    features['score_urgencia_temporal'] = 100 - features['Completude (%)']

    # Dias mínimos para expirar (estimativa)
    features['dias_min_expirar'] = features['Qtd Faltante'] * 90

    # Codificar nível
    le_nivel = LabelEncoder()
    features['nivel_cod'] = le_nivel.fit_transform(features['Nível'])

    # One-hot encoding do nível
    dummies = pd.get_dummies(features['Nível'], prefix='nivel')
    features = pd.concat([features, dummies], axis=1)

    # Selecionar colunas numéricas para o modelo
    colunas_numericas = ['Idade', 'Prioridade', 'microarea_cod',
                         'score_urgencia_temporal', 'dias_min_expirar']
    colunas_numericas += [c for c in dummies.columns]

    X = features[colunas_numericas].fillna(0)
    y_class = features['Prioridade']
    y_reg = features['dias_min_expirar']

    return X, y_class, y_reg, le_micro, le_nivel, features

