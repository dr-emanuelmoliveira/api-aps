def _normalizar_texto(texto):
    """Normaliza texto para comparação (minúsculas, sem acentos, sem espaços extras)."""
    if not isinstance(texto, str):
        return ""
    texto = texto.lower()
    texto = re.sub(r'[áàãâä]', 'a', texto)
    texto = re.sub(r'[éèêë]', 'e', texto)
    texto = re.sub(r'[íìîï]', 'i', texto)
    texto = re.sub(r'[óòõôö]', 'o', texto)
    texto = re.sub(r'[úùûü]', 'u', texto)
    texto = re.sub(r'[ç]', 'c', texto)
    texto = re.sub(r'[^a-z0-9\s]', '', texto) # Remove caracteres especiais
    return ' '.join(texto.split()) # Remove múltiplos espaços e trim

def _parse_data(data_str):
    """Tenta converter string para data, suportando múltiplos formatos."""
    if pd.isna(data_str) or str(data_str).strip() == '':
        return pd.NaT
    data_str = str(data_str).strip()
    formatos = [
        '%d/%m/%Y', '%d/%m/%y', # 28/07/2023, 28/07/23
        '%Y-%m-%d',             # 2023-07-28
        '%d-%m-%Y', '%d-%m-%y', # 28-07-2023, 28-07-23
        '%Y/%m/%d',             # 2023/07/28
        '%m/%d/%Y', '%m/%d/%y', # 07/28/2023, 07/28/23
    ]
    for fmt in formatos:
        try:
            return datetime.strptime(data_str, fmt)
        except ValueError:
            pass
    return pd.NaT

