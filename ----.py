def carregar_e_usar_modelo(caminho_modelo, caminho_csv):
    """
    Carrega um modelo salvo e aplica em um novo CSV.
    Detecta automaticamente o indicador do novo CSV.
    """
    # Carregar modelo
    modelo = joblib.load(caminho_modelo)
    print(f"\n📂 Modelo carregado: {caminho_modelo}")
    print(f"   Indicador original: {modelo['codigo_indicador']}")

    # Carregar novo CSV
    skiprows = detectar_skiprows(caminho_csv)
    try:
        df = pd.read_csv(caminho_csv, sep=';', skiprows=skiprows, encoding='utf-8')
    except Exception:
        df = pd.read_csv(caminho_csv, sep=';', skiprows=skiprows, encoding='latin-1')

    # Detectar indicador do novo CSV
    codigo_novo = detectar_indicador(df.columns)

    if codigo_novo != modelo['codigo_indicador']:
        print(f"\n⚠️  Atenção: O CSV inserido corresponde ao indicador {codigo_novo},")
        print(f"   mas o modelo foi treinado para {modelo['codigo_indicador']}.")
        print(f"   Recomenda-se treinar um novo modelo para este indicador.")
        return None

    # Preparar dados e aplicar modelo
    dados, mapeamento = preparar_dados(df, codigo_novo)
    df_resultado = verificar_criterios(dados, codigo_novo)
    X, _, _, le_micro, le_nivel, features = criar_features_ml(
        df_resultado, dados, codigo_novo
    )

    # Garantir que as features batem
    for col in modelo['colunas_features']:
        if col not in X.columns:
            X[col] = 0
    X = X[modelo['colunas_features']]

    # Prever
    df_previsao = prever_consultas(
        modelo['classificador'], modelo['regressor'],
        X, features, codigo_novo
    )

    return df_previsao

