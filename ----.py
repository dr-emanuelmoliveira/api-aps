def relatorio_completude(df_resultado, codigo_indicador):
    """Gera relatório de completude por microárea."""
    rel = df_resultado.groupby('Microárea').agg({
        'Nome': 'count',
        'Completude (%)': 'mean',
        'Qtd Faltante': 'mean',
        'Prioridade': 'mean'
    }).round(2)

    rel.columns = ['Total de Pacientes', 'Completude Média (%)',
                   'Média de Critérios Faltantes', 'Prioridade Média']
    rel = rel.sort_values('Prioridade Média', ascending=False)

    nome_arq = f'relatorio_completude_{codigo_indicador}.csv'
    rel.to_csv(nome_arq, encoding='utf-8-sig', sep=';')

    print(f"\n📊 Relatório de completude por microárea:")
    print(f"   Arquivo: {nome_arq}")
    print(rel.to_string())

    return rel

