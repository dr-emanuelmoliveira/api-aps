def salvar_modelo(clf, reg, le_micro, le_nivel, codigo_indicador,
                  colunas_features, boas_praticas):
    """
    Salva o modelo treinado em arquivo .pkl para reuso com
    qualquer CSV de qualquer indicador.
    """
    modelo_bundle = {
        'codigo_indicador': codigo_indicador,
        'nome_indicador': INDICADORES[codigo_indicador]['nome'],
        'classificador': clf,
        'regressor': reg,
        'label_encoder_microarea': le_micro,
        'label_encoder_nivel': le_nivel,
        'colunas_features': colunas_features,
        'boas_praticas': boas_praticas,
        'config_indicador': INDICADORES[codigo_indicador],
        'data_treinamento': datetime.now().strftime('%d/%m/%Y %H:%M:%S'),
        'versao': '1.0',
    }

    nome_arq = f'modelo_busca_ativa_{codigo_indicador}.pkl'
    joblib.dump(modelo_bundle, nome_arq)

    print(f"\n{'='*60}")
    print(f"  MODELO SALVO COM SUCESSO")
    print(f"{'='*60}")
    print(f"  Arquivo: {nome_arq}")
    print(f"  Indicador: {codigo_indicador} — {INDICADORES[codigo_indicador]['nome']}")
    print(f"  Data: {modelo_bundle['data_treinamento']}")
    print(f"  Versão: {modelo_bundle['versao']}")
    print(f"  Features: {len(colunas_features)} colunas")
    print(f"  Boas Práticas: {len(boas_praticas)} critérios")
    print(f"{'='*60}")

    return nome_arq

